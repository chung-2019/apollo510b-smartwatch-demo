# -*- coding: utf-8 -*-
"""
Convert the map tiles in docs/map_navigation into RGB565 C arrays for the firmware.

The generated arrays live in MRAM (const) and play the role of the eMMC layer in the
specification document -- the demo does not flash the map into eMMC, but the way
MapTask consumes it is identical to a future eMMC block read (see src/map_store.h).

Usage:
    python tools/map_tile_gen.py

The source tiles come from one master image (2172x724) scaled proportionally to
1404x468 and cut into three. They are horizontally adjacent with continuous content,
so world coordinates are simply "the three images stitched side by side".
"""
import os
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
PROJ = os.path.dirname(HERE)
SRC_DIR = os.path.join(PROJ, "docs", "map_navigation", "taipei101_to_main_station_468_tiles")
OUT_DIR = os.path.join(PROJ, "src", "generated", "map")

#
# The tiles are ordered left to right by world coordinate: x = index * 468.
# The tile_NN file name prefix already carries that order, but the list is still
# written out rather than sorting the directory -- one extra file silently changing
# how the map is stitched would be too dangerous.
#
# Note: the directory and file names below were Chinese in the original project and
# have been romanized here. Rename the source tiles to match, or edit SRC_DIR and TILES.
#
TILES = [
    ("tile_00_taipei_main_station_cks_memorial.png", "map_tile_00", "Taipei Main Station / Chiang Kai-shek Memorial Hall"),
    ("tile_01_daan_forest_park.png",                 "map_tile_01", "Daan Forest Park / Zhongxiao East Road"),
    ("tile_02_sun_yat_sen_memorial_taipei101.png",   "map_tile_02", "Sun Yat-sen Memorial Hall / Taipei 101"),
]

TILE_W = 468
TILE_H = 468


def rgb565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def emit(png_path, symbol, desc, index):
    img = Image.open(png_path).convert("RGB")
    if img.size != (TILE_W, TILE_H):
        raise SystemExit("%s is %s, expected %dx%d" % (png_path, img.size, TILE_W, TILE_H))

    px = img.load()
    out = os.path.join(OUT_DIR, symbol + ".h")

    #
    # The include guard cannot use the conventional <SYMBOL>_H: that would collide with
    # the height macro MAP_TILE_NN_H below and compile into a "redefined" warning. The
    # guard would still work (the name is defined on the second include), but the height
    # macro's value would first be shadowed by the guard's empty definition, and anyone
    # using it would trip over that.
    #
    guard = symbol.upper() + "_INCLUDED"

    with open(out, "w", encoding="utf-8") as f:
        f.write("//*****************************************************************************\n")
        f.write("//\n")
        f.write("//! @file %s.h\n" % symbol)
        f.write("//!\n")
        f.write("//! @brief Map tile %d: %s\n" % (index, desc))
        f.write("//!\n")
        f.write("//! World coordinates x = %d .. %d, %dx%d RGB565 little-endian.\n"
                % (index * TILE_W, (index + 1) * TILE_W - 1, TILE_W, TILE_H))
        f.write("//!\n")
        f.write("//! Generated by tools/map_tile_gen.py from the PNGs in docs/map_navigation/. Do not edit by hand.\n")
        f.write("//\n")
        f.write("//*****************************************************************************\n\n")
        f.write("#ifndef %s\n#define %s\n\n" % (guard, guard))
        f.write("#include <stdint.h>\n\n")
        f.write("#define %s_W  (%d)\n" % (symbol.upper(), TILE_W))
        f.write("#define %s_H  (%d)\n\n" % (symbol.upper(), TILE_H))
        f.write("const uint8_t %s[%d] =\n{\n" % (symbol, TILE_W * TILE_H * 2))

        line = []
        for y in range(TILE_H):
            for x in range(TILE_W):
                r, g, b = px[x, y]
                v = rgb565(r, g, b)
                line.append("0x%02x,0x%02x," % (v & 0xFF, v >> 8))
                if len(line) == 12:
                    f.write("    " + "".join(line) + "\n")
                    line = []
        if line:
            f.write("    " + "".join(line) + "\n")
        f.write("};\n\n#endif // %s\n" % guard)

    print("  %-14s %s (%d bytes)" % (symbol, os.path.basename(out),
                                     os.path.getsize(out)))


def main():
    if not os.path.isdir(SRC_DIR):
        raise SystemExit("source tile directory not found: %s" % SRC_DIR)
    os.makedirs(OUT_DIR, exist_ok=True)

    print("map tiles -> RGB565 C arrays")
    print("  source: %s" % SRC_DIR)
    print("  output: %s" % OUT_DIR)
    for i, (png, symbol, desc) in enumerate(TILES):
        path = os.path.join(SRC_DIR, png)
        if not os.path.isfile(path):
            raise SystemExit("missing tile: %s" % path)
        emit(path, symbol, desc, i)

    total = len(TILES) * TILE_W * TILE_H * 2
    print("  %d tiles, %d bytes of MRAM (%.2f MB)"
          % (len(TILES), total, total / 1024.0 / 1024.0))


if __name__ == "__main__":
    main()
